from pydantic import BaseModel, Field
from app.models.enums import RecoveryAction


class GroundTruth(BaseModel):
    """
    Represents the expected outcome for a synthetic case.

    This is manually generated by deterministic scenario rules,
    not by the LLM. It will later be used to evaluate whether the
    recovery agent made the correct decision.
    """

    expected_action: RecoveryAction

    expected_recoverable: bool

    expected_recovery_probability: float = Field(
        ge=0.0,
        le=1.0,
        description="Probability of successful recovery between 0.0 and 1.0."
    )

    reason: str = Field(
        min_length=1,
        description="Deterministic explanation of why this ground truth decision was assigned."
    )
